#!/usr/bin/env node
/**
 * Fill remaining photo gaps so the whole catalogue is photographic.
 *
 * Openverse has no CC0 result for every demo product. Rather than mixing real
 * photography with vector artwork, a product without its own photo borrows the
 * photo of a sibling in the same subcategory (a related product), copied to its
 * own file. Nothing is hotlinked and every URL stays local.
 *
 *   node scripts/fill-photos.mjs
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { DEPARTMENTS } from '../server/catalogue-data.js';

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, 'public', 'catalogue');
const STATE_FILE = path.join(OUT_DIR, 'photos.json');
const MAP_FILE = path.join(ROOT, 'server', 'catalogue-photos.js');

const slugify = (s) =>
  String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 70);

async function main() {
  let state = {};
  try {
    state = JSON.parse(await fs.readFile(STATE_FILE, 'utf8'));
  } catch {
    console.error('No photo state yet — run scripts/fetch-photos.mjs first.');
    process.exit(1);
  }

  // Group catalogue products by subcategory so siblings can lend a photo.
  const groups = new Map();
  for (const dept of DEPARTMENTS) {
    for (const sub of dept.subs) {
      const key = `${dept.slug}::${sub.name}`;
      const list = groups.get(key) || [];
      for (const [name] of sub.nouns || []) list.push(name);
      groups.set(key, list);
    }
  }

  // Pass 1: borrow from a sibling in the same subcategory.
  let filled = 0;
  const copyFrom = async (name, donor) => {
    const target = path.join(OUT_DIR, `${slugify(name)}.jpg`);
    await fs.copyFile(path.join(ROOT, 'public', state[donor].path), target);
    state[name] = { path: `/catalogue/${slugify(name)}.jpg`, borrowedFrom: donor };
    filled += 1;
  };

  for (const names of groups.values()) {
    const donors = names.filter((n) => state[n]?.path);
    if (!donors.length) continue;
    let turn = 0;
    for (const name of names) {
      if (state[name]?.path) continue;
      const donor = donors[turn % donors.length];
      turn += 1;
      try {
        await copyFrom(name, donor);
      } catch (err) {
        console.error(`✗ ${name}: ${err.message}`);
      }
    }
  }

  // Pass 2: any remaining product borrows from its own department, then from the
  // whole catalogue, so every product resolves to a local photograph.
  const allDonors = Object.entries(state)
    .filter(([, v]) => v?.path && !v.borrowedFrom)
    .map(([n]) => n);
  const deptOf = new Map();
  for (const dept of DEPARTMENTS) {
    for (const sub of dept.subs) for (const [name] of sub.nouns || []) deptOf.set(name, dept.slug);
  }
  let turn = 0;
  for (const [name, dept] of deptOf) {
    if (state[name]?.path) continue;
    const sameDept = allDonors.filter((d) => deptOf.get(d) === dept);
    const donor = sameDept[turn % Math.max(sameDept.length, 1)] || allDonors[turn % allDonors.length];
    turn += 1;
    if (!donor) continue;
    try {
      await copyFrom(name, donor);
    } catch (err) {
      console.error(`✗ ${name}: ${err.message}`);
    }
  }

  await fs.writeFile(STATE_FILE, `${JSON.stringify(state, null, 2)}\n`);
  const map = {};
  for (const [name, value] of Object.entries(state)) if (value?.path) map[name] = value.path;
  await fs.writeFile(
    MAP_FILE,
    `/**\n * Generated by scripts/fetch-photos.mjs — do not edit by hand.\n *\n * Maps a catalogue product name to locally hosted, CC0 / public-domain\n * photography under public/catalogue/. Regenerate with:\n *   node scripts/fetch-photos.mjs --limit 40 --offset 0\n */\nexport const PHOTOS = ${JSON.stringify(map, null, 2)};\n`
  );
  console.log(`filled ${filled} products, mapped ${Object.keys(map).length} total`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
